"""ANIM-024: TDD for target rig discovery. No Unreal changes in these tests."""
import sys, unittest
from pathlib import Path
from unittest.mock import Mock
sys.path.insert(0,str(Path(__file__).resolve().parents[2]/"tools"/"assetforge"))
from anim024_target_preflight import (
    validate_snapshot, validate_manual_mapping, build_target_review,
    inspect_target_in_unreal, required_plugin_settings,
)

SOURCE_CHAINS={
 "Root":("root","pelvis"),"Spine":("pelvis","chest"),"Head":("neck","head"),
 "LeftArm":("upper_arm_L","hand_L"),"RightArm":("upper_arm_R","hand_R"),
 "LeftLeg":("thigh_L","foot_L"),"RightLeg":("thigh_R","foot_R")}
BONES={
 "root":None,"pelvis":"root","spine":"pelvis","chest":"spine","neck":"chest","head":"neck",
 "upper_arm_L":"chest","lower_arm_L":"upper_arm_L","hand_L":"lower_arm_L",
 "upper_arm_R":"chest","lower_arm_R":"upper_arm_R","hand_R":"lower_arm_R",
 "thigh_L":"pelvis","calf_L":"thigh_L","foot_L":"calf_L",
 "thigh_R":"pelvis","calf_R":"thigh_R","foot_R":"calf_R"}
def snapshot():
    return {"schema":"naris.anim024.target-skeleton.v1","skeletal_mesh_object_path":"/Game/Review/SK_Target.SK_Target",
            "engine_version":"5.7.3","bones":[{"name":n,"parent":p} for n,p in BONES.items()],
            "is_unreal_editor_capture":True,"asset_modified":False}
def mapping():
    return {"schema":"naris.anim024.manual-retarget-map.v1","target_retarget_root":"pelvis",
            "chains":{name:{"start":a,"end":b} for name,(a,b) in SOURCE_CHAINS.items()},
            "explicitly_approved":False}

class TargetContract(unittest.TestCase):
    def test_read_only_snapshot_has_valid_hierarchy(self):
        x=validate_snapshot(snapshot())
        self.assertEqual(len(x["parents"]),18)
        self.assertEqual(x["root"],"root")
    def test_missing_parent_rejected(self):
        a=snapshot();a["bones"][2]["parent"]="does_not_exist"
        with self.assertRaises(ValueError): validate_snapshot(a)
    def test_duplicate_bone_rejected(self):
        a=snapshot();a["bones"].append({"name":"hand_L","parent":"lower_arm_L"})
        with self.assertRaises(ValueError):validate_snapshot(a)
    def test_parent_cycle_rejected(self):
        a=snapshot();a["bones"][0]["parent"]="pelvis"
        with self.assertRaises(ValueError):validate_snapshot(a)
    def test_multiple_root_rejected(self):
        a=snapshot();a["bones"][1]["parent"]=None
        with self.assertRaises(ValueError):validate_snapshot(a)
    def test_unreal_capture_not_claimed_when_false(self):
        a=snapshot();a["is_unreal_editor_capture"]=False
        result=validate_snapshot(a)
        self.assertFalse(result["engine_evidence"])
    def test_wrong_engine_rejected(self):
        a=snapshot();a["engine_version"]="5.6.3"
        with self.assertRaises(ValueError):validate_snapshot(a)
    def test_wrong_object_path_rejected(self):
        a=snapshot();a["skeletal_mesh_object_path"]="/Engine/SK_Mannequin"
        with self.assertRaises(ValueError):validate_snapshot(a)
    def test_retarget_seven_verified_but_not_approved(self):
        q=build_target_review(snapshot(),mapping())
        self.assertEqual(q["verified_chain_count"],7)
        self.assertEqual(q["retargeter_asset"],"NOT_CREATED")
        self.assertFalse(q["production_ready"])
    def test_missing_chain_rejected(self):
        m=mapping();m["chains"].pop("Head")
        with self.assertRaises(ValueError):validate_manual_mapping(snapshot(),m)
    def test_unexpected_autogenerated_chain_rejected(self):
        m=mapping();m["chains"]["Extra"]=dict(start="root",end="head")
        with self.assertRaises(ValueError):validate_manual_mapping(snapshot(),m)
    def test_direction_of_chain_must_be_ancestral(self):
        m=mapping();m["chains"]["LeftLeg"]=dict(start="foot_L",end="thigh_L")
        with self.assertRaises(ValueError):validate_manual_mapping(snapshot(),m)
    def test_cross_limb_chain_must_be_blocked(self):
        m=mapping();m["chains"]["RightArm"]=dict(start="upper_arm_R",end="hand_L")
        with self.assertRaises(ValueError):validate_manual_mapping(snapshot(),m)
    def test_retarget_root_must_match_root_chain_end(self):
        m=mapping();m["target_retarget_root"]="head"
        with self.assertRaises(ValueError):validate_manual_mapping(snapshot(),m)
    def test_uncaptured_snapshot_will_not_be_approved(self):
        a=snapshot();a["is_unreal_editor_capture"]=False
        q=build_target_review(a,mapping())
        self.assertFalse(q["verified_in_engine"])
        self.assertFalse(q["production_ready"])
    def test_editor_capture_uses_skeleton_modifier_read_only(self):
        class Modifier:
            def __init__(self):self.mesh=None
            def set_skeletal_mesh(self,mesh):self.mesh=mesh;return True
            def get_all_bone_names(self):return list(BONES)
            def get_parent_name(self,bone):return BONES[bone] if BONES[bone] else "None"
        modifier=Modifier()
        unreal=Mock()
        unreal.SystemLibrary.get_engine_version.return_value="5.7.3"
        unreal.load_asset.return_value=object()
        unreal.SkeletalMesh=type(unreal.load_asset.return_value)
        unreal.SkeletonModifier.return_value=modifier
        result=inspect_target_in_unreal(unreal,"/Game/Review/SK_Target.SK_Target")
        self.assertEqual(len(result["bones"]),18)
        self.assertTrue(result["is_unreal_editor_capture"])
        self.assertFalse(result["asset_modified"])
        self.assertFalse(hasattr(modifier,"commit_skeleton_to_skeletal_mesh"))
    def test_editor_does_not_assume_missing_asset(self):
        unreal=Mock()
        unreal.SystemLibrary.get_engine_version.return_value="5.7"
        unreal.load_asset.return_value=None
        with self.assertRaises(ValueError):
            inspect_target_in_unreal(unreal,"/Game/Review/SK_Target.SK_Target")
    def test_plugins_not_explicitly_enabled_are_reported(self):
        uproject={"Plugins":[{"Name":"PythonScriptPlugin","Enabled":True}]}
        q=required_plugin_settings(uproject)
        self.assertIn("IKRig",q["missing_explicit_enablement"])
        self.assertIn("MeshModelingToolset",q["missing_explicit_enablement"])
        self.assertFalse(q["project_metadata_preflight_pass"])
    def test_untrusted_explicit_approval_cannot_override_missing_asset(self):
        a=snapshot();a["is_unreal_editor_capture"]=False
        m=mapping();m["explicitly_approved"]=True
        self.assertFalse(build_target_review(a,m)["production_ready"])
if __name__=="__main__":unittest.main()
